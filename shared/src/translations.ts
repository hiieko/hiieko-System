export function t(key: string, locale: Locale = 'ro'): string {
  const e = d[key];
  if (!e) return key;
  return e[locale] ?? e['ro'] ?? key;
}

export function tPrefix(prefix: string, locale: Locale = 'ro'): Record<string, string> {
  const r: Record<string, string> = {};
  for (const [k, v] of Object.entries(d)) {
    if (k.startsWith(prefix)) r[k] = v[locale] ?? v['ro'];
  }
  return r;
}

